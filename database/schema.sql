-- Water Usage Tracking Dashboard schema
-- This starter app is intended for a local classroom demo. The backend uses the
-- Supabase service-role key, which bypasses RLS. Never expose the server publicly
-- without adding real authentication and per-user authorization.
create table if not exists public.water_readings (
  id bigint generated by default as identity primary key,
  reading_date date not null unique,
  meter_reading_m3 numeric(12,3) not null check (meter_reading_m3 >= 0),
  category text not null default 'Household' check (category in ('Household','Bathroom','Kitchen','Laundry','Garden','Cleaning','Other')),
  notes text check (notes is null or char_length(notes) <= 500),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.dashboard_settings (
  id smallint primary key default 1 check (id = 1),
  daily_target_m3 numeric(10,3) not null default 0.500 check (daily_target_m3 > 0),
  updated_at timestamptz not null default now()
);

create index if not exists water_readings_date_idx on public.water_readings (reading_date desc);
create index if not exists water_readings_category_date_idx on public.water_readings (category, reading_date desc);

create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists water_readings_set_updated_at on public.water_readings;
create trigger water_readings_set_updated_at before update on public.water_readings
for each row execute function public.set_updated_at();
drop trigger if exists dashboard_settings_set_updated_at on public.dashboard_settings;
create trigger dashboard_settings_set_updated_at before update on public.dashboard_settings
for each row execute function public.set_updated_at();

insert into public.dashboard_settings (id, daily_target_m3)
values (1, 0.500)
on conflict (id) do nothing;

-- RLS is enabled as a safety baseline. This server-side starter uses the service
-- role key and therefore bypasses RLS; no public/anon policies are created.
alter table public.water_readings enable row level security;
alter table public.dashboard_settings enable row level security;
